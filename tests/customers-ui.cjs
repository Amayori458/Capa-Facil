const { chromium } = require('playwright');
const fs = require('fs');
const assert = require('node:assert/strict');
const path = require('path');
(async () => {
  const browser = await chromium.launch({channel:'msedge',headless:true});
  const page = await browser.newPage({viewport:{width:1280,height:900}});
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  let sessionRole='admin', failSave=false, failLoad=false;
  let users=[{id:'1',nome:'Administrador',usuario:'admin',role:'admin',ativo:true},{id:'2',nome:'Ana "Oliveira"',usuario:'ana',whatsapp:'11999998888',role:'cliente',ativo:true},{id:'3',nome:'João Silva',usuario:'joao',role:'cliente',ativo:false}];
  const writes=[];
  await page.route('**/*',async route=>{
    const url=new URL(route.request().url());
    if(url.hostname!=='app.local') return route.abort();
    const json=(body,status=200)=>route.fulfill({status,contentType:'application/json',body:JSON.stringify(body)});
    if(url.pathname==='/') return route.fulfill({contentType:'text/html',body:fs.readFileSync(path.join(__dirname,'../index.html'),'utf8')});
    if(url.pathname==='/api/me') return json({id:'1',nome:'Administrador',usuario:'admin',role:sessionRole});
    if(url.pathname==='/api/usuarios') {
      if(route.request().method()==='GET') return failLoad ? json({error:'Falha simulada'},500) : json({usuarios:users});
      const body=route.request().postDataJSON(); writes.push(body);
      await new Promise(r=>setTimeout(r,150));
      if(failSave) return json({error:'Já existe um usuário com esse nome de acesso.'},400);
      if(route.request().method()==='POST') users.push({...body,id:String(users.length+1),role:body.role||'cliente',ativo:true});
      else Object.assign(users.find(u=>u.id===body.id),body);
      return json({ok:true});
    }
    if(url.pathname==='/api/pedidos') return json({pedidos:[]});
    return json({assets:[],icons:[],fonts:[]});
  });
  await page.goto('http://app.local');
  await page.locator('#btn-open-admin').click();
  await page.locator('[data-admin-tab=clientes]').click();
  await page.getByRole('heading',{name:'Clientes e cadastros'}).waitFor();
  await page.getByLabel('Buscar cadastro').fill('joao');
  assert.equal(await page.locator('.customer-row:visible').count(),1);
  await page.getByLabel('Buscar cadastro').fill('');
  await page.locator('#admin-customers-status').selectOption('blocked');
  assert.equal(await page.locator('.customer-row:visible').count(),1);
  await page.locator('#admin-customers-status').selectOption('');
  await page.locator('.customer-row[data-id="2"] [data-edit]').click();
  assert.equal(await page.getByLabel('Nome completo').inputValue(),'Ana "Oliveira"');
  await page.getByLabel('Nome completo').fill('Ana Oliveira Santos');
  await page.getByRole('button',{name:'Salvar alterações'}).click();
  await page.locator('dialog').waitFor({state:'detached'});
  await page.getByText('Ana Oliveira Santos',{exact:true}).waitFor();
  await page.locator('.customer-row[data-id="1"] [data-edit]').click();
  assert(await page.getByLabel('Perfil de acesso').isDisabled());
  assert(await page.locator('dialog select[name=ativo]').isDisabled());
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'Novo cadastro'}).click();
  await page.getByLabel('Nome completo').fill('Novo Cliente');
  await page.getByLabel('Usuário de acesso').fill('novo');
  await page.locator('input[name=senha]').fill('123');
  await page.getByRole('button',{name:'Criar cadastro',exact:true}).click();
  assert.equal(writes.length,1);
  await page.locator('input[name=senha]').fill('senha123');
  await page.getByRole('button',{name:'Mostrar',exact:true}).click();
  assert.equal(await page.locator('input[name=senha]').getAttribute('type'),'text');
  failSave=true;
  await page.getByRole('button',{name:'Criar cadastro',exact:true}).click();
  await page.getByText('Já existe um usuário com esse nome de acesso.',{exact:true}).waitFor();
  assert.equal(await page.getByLabel('Nome completo').inputValue(),'Novo Cliente');
  failSave=false;
  await page.getByRole('button',{name:'Criar cadastro',exact:true}).click();
  await page.locator('dialog').waitFor({state:'detached'});
  await page.getByText('Novo Cliente',{exact:true}).waitFor();
  await page.locator('.customer-row[data-id="2"] [data-password]').click();
  await page.locator('input[name=senha]').fill('novasenha123');
  await page.getByRole('button',{name:'Salvar senha',exact:true}).click();
  await page.locator('dialog').waitFor({state:'detached'});
  assert.deepEqual(writes.at(-1),{id:'2',senha:'novasenha123'});
  await page.screenshot({path:process.env.TEMP+'/clientes-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:process.env.TEMP+'/clientes-mobile.png',fullPage:true});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobile page overflow');
  assert(await page.locator('.customers-directory').evaluate(el=>el.scrollWidth<=el.clientWidth),'Mobile directory overflow');
  await page.getByRole('button',{name:'Novo cadastro'}).click();
  assert(await page.locator('dialog').evaluate(el=>el.scrollWidth<=el.clientWidth),'Dialog overflow');
  await page.keyboard.press('Escape');
  await page.emulateMedia({colorScheme:'dark'});
  await page.screenshot({path:process.env.TEMP+'/clientes-dark.png',fullPage:true});
  sessionRole='vendedora';users=users.filter(u=>u.role==='cliente');
  await page.goto('http://app.local');
  await page.locator('[data-vendedora-tab=clientes]').click();
  await page.getByRole('heading',{name:'Meus clientes'}).waitFor();
  await page.getByRole('button',{name:'Novo cliente',exact:false}).click();
  assert.equal(await page.locator('dialog select[name=role]').count(),0);
  await page.keyboard.press('Escape');
  failLoad=true;
  await page.locator('[data-vendedora-tab=clientes]').click();
  await page.getByText('Não foi possível carregar os cadastros',{exact:true}).waitFor();
  failLoad=false;users=[];
  await page.getByRole('button',{name:'Tentar novamente'}).click();
  await page.getByText('Sua lista começa aqui',{exact:true}).waitFor();
  assert.deepEqual(errors,[]);
  console.log('PASS: search, filters, create, edit, reset password, validation, API error recovery, self-account restrictions, mobile, dark mode, seller permissions, empty state; no browser errors.');
  await browser.close();
})().catch(err=>{console.error(err);process.exit(1)});
